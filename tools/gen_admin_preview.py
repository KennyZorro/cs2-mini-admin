#!/usr/bin/env python3
"""Writes workshop/preview/admin.html, a self-contained browser preview of the !admin menu.

The page embeds the real layout (admin_v1.xml), the real styles (admin_v1.vcss) and the translations
(src/lang/en.json, de.json). workshop/preview/src/preview.js turns them into web elements and CSS and
paints them from sample data like src/AdminMenu.cs does. The game stays authoritative: the preview
only approximates the Panorama layout model.

    python tools/gen_admin_preview.py           write the file
    python tools/gen_admin_preview.py --check   exit 1 if the file is out of date
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LAYOUT = ROOT / "workshop/content/panorama/layout/custom_game/miniadmin/admin_v1.xml"
STYLES = ROOT / "workshop/content/panorama/styles/custom_game/miniadmin/admin_v1.vcss"
LANG = ROOT / "src/lang"
SRC = ROOT / "workshop/preview/src"
OUT = ROOT / "workshop/preview/admin.html"

PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>MiniAdmin Menu Preview</title>
<!-- generated by tools/gen_admin_preview.py - do not edit by hand -->
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Barlow+Condensed:wght@500;600&display=swap" rel="stylesheet">
<style>
%(base)s</style>
</head>
<body>
<div class="pv-bar">
  <b>MiniAdmin · !admin</b>
  <span class="pv-grow">Browser preview built from admin_v1.xml and admin_v1.vcss with sample data. Click through it like in game; the game is authoritative.</span>
  <button id="pv-reopen" class="pv-reopen" type="button">!admin</button>
  <select id="pv-lang" aria-label="Language">
    <option value="en">English</option>
    <option value="de">Deutsch</option>
  </select>
</div>
<div class="pv-viewport"><div class="pv-stage"></div></div>
<script>
window.MA_DATA = %(data)s;
</script>
<script>
%(script)s</script>
</body>
</html>
"""


def read(path: Path) -> str:
    return path.read_text(encoding="utf-8").replace("\r\n", "\n")


def render() -> str:
    data = {
        "xml": read(LAYOUT),
        "vcss": read(STYLES),
        "lang": {name: json.loads(read(LANG / f"{name}.json")) for name in ("en", "de")},
    }
    # "</" would end the script element early
    blob = json.dumps(data, ensure_ascii=False, indent=None, separators=(",", ":")).replace("</", "<\\/")
    return PAGE % {"base": read(SRC / "base.css"), "data": blob, "script": read(SRC / "preview.js")}


def main() -> int:
    page = render()
    if "--check" in sys.argv[1:]:
        current = read(OUT) if OUT.exists() else ""
        if current != page:
            print(f"{OUT.relative_to(ROOT)} is out of date: run tools/gen_admin_preview.py", file=sys.stderr)
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(page, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(page.encode('utf-8')) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
